export function linePairs() {
  return Object.keys(NPC_LINES).map((id) => ({ id, en: NPC_LINES[id].en, ckb: NPC_LINES[id].ckb }));
}

export function npcLine(lang, id) {
  const row = NPC_LINES[id];
  if (!row) return '';
  return lang === 'ckb' ? row.ckb : row.en;
}

export function t(lang, key) {
  const pack = STR[lang] || STR.en;
  if (pack[key] != null) return pack[key];
  return STR.en[key] != null ? STR.en[key] : key;
}

export function formatNum(n, lang) {
  const neg = n < 0;
  const s = String(Math.floor(Math.abs(Number(n) || 0)));
  const out = lang === 'ckb' ? s.replace(/\d/g, (d) => DIGITS[d]) : s;
  return neg ? `-${out}` : out;
}

export function formatClock(hour, acc, lang) {
  const mins = Math.floor((acc / 2) * 60) % 60;
  const text = `${String(hour).padStart(2, '0')}:${String(mins).padStart(2, '0')}`;
  return lang === 'ckb' ? text.replace(/\d/g, (d) => DIGITS[d]) : text;
}
